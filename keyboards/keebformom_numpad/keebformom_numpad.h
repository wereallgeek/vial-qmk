/*
 * KFM PCB mounted rotated 90 degrees COUNTER-CLOCKWISE (-90 deg).
 * The layout macro is generated by QMK from info.json (not defined here).
 *
 * Original board (4 rows x 5 cols, matrix [row][col]):
 *
 *     c0   c1   c2   c3   c4
 * r0  .    .    .    .    .
 * r1  .    .    .    .    .
 * r2  .    .    .    .    .
 * r3  [2u ]  .  [2u ]          <- bottom row: 2u footprints on c0-c1 and c3-c4
 *
 * After the rotation the original top row becomes the LEFT column, the
 * original bottom row (spacebar row) becomes the RIGHT column, and the original
 * right-most column (c4) becomes the TOP row:
 *
 *   visual (R, C)  ->  matrix [r = C][c = 4 - R]
 *
 *        C0   C1   C2   C3
 *   R0   k00  k01  k02  k03  --+  2u (c4+c3)   "+"
 *   R1   k10  k11  k12  k13  --+
 *   R2   k20  k21  k22  k23      1u (c2)       "-"
 *   R3   k30  k31  k32  k33  --+  2u (c1+c0)   Enter
 *   R4   k40  k41  k42  k43  --+
 *
 * Keymap arguments are given in visual order, left to right, top to bottom.
 * Both footprints of a 2u key are kept as separate arguments: put the same
 * keycode on both (or KC_NO on the one you leave empty).
 */
